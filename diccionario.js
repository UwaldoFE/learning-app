const DICC_NOMBRES = new Set("uwaldo maria tom laura sam mark carlos ana anna lyle sofia pedro luis max kathryn paula john ruiz natalia lucas carla mario sue sarah charlie florez lucía lucia alzati sena athens pamplona".split(" "));

// Convierte el texto en un mapa { palabra: significado }
const DICC = (() => {
  const m = Object.create(null);
  DICC_TEXTO.split("\n").forEach((l) => {
    const i = l.indexOf("=");
    if (i > 0) { const k = l.slice(0, i).trim().toLowerCase(); if (!(k in m)) m[k] = l.slice(i + 1).trim(); }
  });
  return m;
})();

// Busca una palabra. Si viene conjugada (works, worked, working, bigger, quickly, Laura's…)
// busca su forma base. Devuelve { es, base, nota } o null si no la encuentra.
function buscarEnDiccionario(palabraOriginal) {
  const w = String(palabraOriginal).toLowerCase().replace(/[’`´]/g, "'").replace(/^'+|'+$/g, "");
  if (!w) return null;
  if (DICC[w]) return { es: DICC[w] };
  if (DICC_NOMBRES.has(w)) return { es: "nombre propio (persona, marca o lugar)" };
  if (/^\d+([.,]\d+)?(st|nd|rd|th)?$/.test(w)) return { es: "número" };
  const intentar = (base, nota) => (DICC[base] ? { es: DICC[base], base, nota } : null);
  // posesivo: Laura's, brother's, students'
  if (/'s$/.test(w) || /s'$/.test(w)) {
    const base = w.replace(/'s$|'$/, "");
    const r = buscarEnDiccionario(base);
    if (r) return { es: r.es, base: r.base || base, nota: "'s = de (posesivo): " + (r.base || base) + "'s = de " + (r.base || base) };
    return { es: "de " + base, nota: "'s = de (posesivo)" };
  }
  // contracciones sin apóstrofo (dont, im, isnt…)
  const sinApo = { dont: "don't", doesnt: "doesn't", didnt: "didn't", isnt: "isn't", arent: "aren't", wasnt: "wasn't", werent: "weren't",
    cant: "can't", wont: "won't", im: "i'm", ive: "i've", ill: "i'll", id: "i'd", youre: "you're", hes: "he's", shes: "she's",
    theyre: "they're", thats: "that's", whats: "what's", theres: "there's", havent: "haven't", hasnt: "hasn't", lets: "let's" };
  if (sinApo[w] && DICC[sinApo[w]]) return { es: DICC[sinApo[w]], nota: `Se escribe con apóstrofo: ${sinApo[w]}` };
  const reglas = [
    [/ies$/, "y", "plural o verbo con he/she/it"], [/(ss|sh|ch|x|o)es$/, "$1", "plural o verbo con he/she/it"], [/s$/, "", "plural o verbo con he/she/it"],
    [/ied$/, "y", "pasado"], [/([b-df-hj-np-tv-z])\1ed$/, "$1", "pasado"], [/ed$/, "e", "pasado"], [/ed$/, "", "pasado"], [/d$/, "", "pasado"],
    [/([b-df-hj-np-tv-z])\1ing$/, "$1", "-ing: acción en curso"], [/ing$/, "e", "-ing: acción en curso"], [/ing$/, "", "-ing: acción en curso"],
    [/ier$/, "y", "comparativo: más …"], [/([b-df-hj-np-tv-z])\1er$/, "$1", "comparativo: más …"], [/er$/, "e", "comparativo: más …"], [/er$/, "", "comparativo: más …"],
    [/iest$/, "y", "superlativo: el más …"], [/([b-df-hj-np-tv-z])\1est$/, "$1", "superlativo: el más …"], [/est$/, "e", "superlativo: el más …"], [/est$/, "", "superlativo: el más …"],
    [/ily$/, "y", "adverbio (-ly = -mente)"], [/ly$/, "", "adverbio (-ly = -mente)"]
  ];
  for (const [re, rep, nota] of reglas) {
    if (!re.test(w)) continue;
    const base = w.replace(re, rep);
    if (base.length < 2 || base === w) continue;
    const r = intentar(base, nota);
    if (r) return r;
  }
  return null;
}
